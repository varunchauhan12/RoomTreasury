function confirm(write:Awaited<ReturnType<typeof fixture>>['write']){
 const quote=write({action:'submit',amountCents:10000,reference:'Quote V1'}).quote!;
 write({action:'accept',quoteId:quote.id,reference:'Client signature received'});
 return write({action:'agreement',quoteId:quote.id,amountCents:10000,signedOn:'2026-08-01',terms:'Net 14',reference:'Signed agreement evidence'});
}
test('commercial proposal revisions, signed terms and project delivery stay separate from financial activation',async t=>{
 const f=await fixture(t);
 const first=f.write({action:'submit',amountCents:12000,reference:'Version 1'}).quote!;
 assert.equal(f.ledger.snapshot(f.session,f.id).agreedCents,null);
 f.write({action:'revision_requested',quoteId:first.id,reference:'Client asked for scope changes'});
 const second=f.write({action:'submit',amountCents:10000,reference:'Version 2'}).quote!;
 assert.equal(second.revision,2);
 assert.throws(()=>f.write({action:'accept',quoteId:first.id,reference:'Wrong revision'}),{code:'PROPOSAL_TRANSITION_INVALID'});
 f.write({action:'accept',quoteId:second.id,reference:'Client accepted V2'});
 assert.throws(()=>f.write({action:'agreement',quoteId:second.id,amountCents:12000,signedOn:'2026-08-01',terms:'Net 14',reference:'Agreement'}),{code:'AGREEMENT_MUST_MATCH_ACCEPTED_QUOTE'});
 assert.throws(()=>f.write({action:'agreement',quoteId:second.id,amountCents:10000,signedOn:'2026-08-01',terms:'Net 14',reference:'  '}),{code:'REFERENCE_OR_TERMS_REQUIRED'});
 const confirmed=f.write({action:'agreement',quoteId:second.id,amountCents:10000,signedOn:'2026-08-01',terms:'Net 14',reference:'Agreement'});
 assert.equal(confirmed.agreedCents,10000);
 assert.equal(confirmed.cashCents,0);
 assert.throws(()=>f.write({action:'delivery_start',reference:'Kickoff held'}),{code:'FINAL_ACTIVATION_REQUIRED'});
 assert.throws(()=>f.write({action:'complete',reference:'Too early'}),{code:'DELIVERY_OR_RECEIVABLES_UNRESOLVED'});
 f.write({action:'receipt',amountCents:10000,date:'2026-08-10',method:'ACH',reference:'DEMO-payment'});
 f.write({action:'expense',amountCents:2300,date:'2026-08-10',method:'Card',reference:'DEMO-expense'});
 assert.throws(()=>f.write({action:'complete',reference:'Client acceptance of delivered work'}),{code:'DELIVERY_OR_RECEIVABLES_UNRESOLVED'});
 assert.equal(f.ledger.snapshot(f.session,f.id).recordedMarginCents,null);
 assert.equal(f.db.prepare('SELECT financial_project_id FROM client_projects WHERE id=?').pluck().get(f.id),null);
 for(const table of ['projects','commitments','reservations','settlement_receipts'])assert.equal(f.db.prepare('SELECT count(*) FROM '+table).pluck().get(),0);
});
test('invoice state, partial payment, overdue balance and idempotent full payment derive from immutable rows',async t=>{
 const f=await fixture(t);confirm(f.write);
 const cancelled=f.write({action:'invoice_draft',number:'AUDIT-CANCEL',amountCents:1000,dueOn:'2026-08-15'}).invoices[0]!;
 assert.equal(f.write({action:'invoice_cancel',invoiceId:cancelled.id,reference:'Replaced before issue'}).invoices[0]!.status,'cancelled');
 const draft=f.write({action:'invoice_draft',number:'AUDIT-001',amountCents:10000,dueOn:'2026-08-15'}).invoices[0]!;
 assert.equal(draft.status,'draft');
 assert.equal(draft.outstandingCents,0);
 assert.throws(()=>f.write({action:'receipt',invoiceId:draft.id,amountCents:1,date:'2026-08-12',method:'ACH',reference:'not payable'}),{code:'PAYMENT_EXCEEDS_OUTSTANDING_OR_INVOICE_NOT_PAYABLE'});
 const issued=f.write({action:'invoice_issue',invoiceId:draft.id,date:'2026-08-10'});
 assert.equal(issued.invoices[0]!.status,'issued');
 assert.equal(issued.receivableCents,10000);
 assert.equal(issued.cashCents,0);
 const receipt={action:'receipt',invoiceId:draft.id,amountCents:4000,date:'2026-08-12',method:'ACH',reference:'PAY-01'} as const;
 const partial=f.write(receipt,'payment-one');
 assert.equal(partial.invoices[0]!.status,'partially_paid');
 assert.equal(partial.receivableCents,6000);
 assert.equal(f.write(receipt,'payment-one').cashCents,4000);
 assert.throws(()=>f.write({...receipt,amountCents:1},'payment-one'),{code:'IDEMPOTENCY_CONFLICT'});
 assert.throws(()=>f.write({...receipt,reference:'pay-01'}),{code:'DUPLICATE_PAYMENT_REFERENCE'});
 assert.throws(()=>f.write({action:'invoice_cancel',invoiceId:draft.id,reference:'Cannot cancel paid balance'}),{code:'INVOICE_CANCEL_INVALID'});
 const overdue=new CommercialLedger(f.db,()=>now+86400000).snapshot(f.session,f.id);
 assert.equal(overdue.invoices[0]!.status,'overdue');
 assert.equal(overdue.invoices[0]!.paidCents,4000);
 assert.equal(overdue.overdueCount,1);
 assert.throws(()=>f.write({...receipt,amountCents:6001,reference:'too much'}),{code:'PAYMENT_EXCEEDS_OUTSTANDING_OR_INVOICE_NOT_PAYABLE'});
 const paid=f.write({...receipt,amountCents:6000,reference:'PAY-02'});
 assert.equal(paid.invoices[0]!.status,'paid');
 assert.equal(paid.invoices[0]!.receiptIds.length,2);
 assert.deepEqual(f.ledger.dashboard(f.session).totals,{contractedCents:10000,cashCents:10000,receivableCents:0,overdueCount:0,expenseCents:0});
 assert.equal(paid.events[0]!.owner_id,f.ownerId);
 assert.throws(()=>f.db.prepare('DELETE FROM commercial_cash').run(),/immutable/);
});
