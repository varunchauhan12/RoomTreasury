test('revised quotes need fresh client acceptance and same-value signed endorsement while original contract and invoices remain immutable',async t=>{
 const f=await fixture(t);const original=confirm(f.write).agreement!;
 const invoice=f.write({action:'invoice_draft',number:'ORIGINAL-CONTRACT',amountCents:10000,dueOn:'2026-08-15'}).invoices[0]!;
 const before=f.db.prepare('SELECT * FROM commercial_agreements').all();
 assert.throws(()=>f.write({action:'submit',amountCents:11000,reference:'Changed contract value'}),{code:'CONTRACT_AMOUNT_AMENDMENTS_DEFERRED'});
 const q=f.write({action:'submit',amountCents:10000,reference:'New technical proposal; price preserved'}).quote!;
 assert.equal(f.ledger.snapshot(f.session,f.id).stage,'submitted');
 assert.throws(()=>f.write({action:'agreement',quoteId:q.id,amountCents:10000,signedOn:'2026-08-02',terms:'Net 14',reference:'Unsigned new version'}),{code:'ACCEPTED_REVISION_REQUIRED'});
 f.write({action:'accept',quoteId:q.id,reference:'Client accepted new technical scope'});
 const endorsed=f.write({action:'agreement',quoteId:q.id,amountCents:10000,signedOn:'2026-08-02',terms:'Net 14',reference:'Signed endorsement for revised scope'});
 assert.equal(endorsed.agreement!.id,original.id);
 assert.equal(endorsed.agreement!.quote_id,q.id);
 assert.equal(endorsed.invoices[0]!.id,invoice.id);
 assert.deepEqual(f.db.prepare('SELECT * FROM commercial_agreements').all(),before);
 assert.equal(f.db.prepare('SELECT count(*) FROM commercial_agreement_endorsements').pluck().get(),1);
 assert.throws(()=>f.db.exec('DELETE FROM commercial_agreement_endorsements'),/retain/);
});
